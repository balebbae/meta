// Seeds the general "For you" Reels (feed_reels). Usage: node --env-file=.env.local scripts/seed-feed-reels.mjs [--limit N] [--no-db]
//
// Pixabay Videos API (PIXABAY_API_KEY) -> everyday clips (city, food, pets, travel...), portrait preferred.
// Writes db/feed-reels-fixture.json + db/seed-feed-reels.sql (used by db:setup on a fresh database) and,
// unless --no-db, upserts into feed_reels. Without a key the checked-in fixture is reused.
// No Muse here: these are ordinary Reels; the fitness library (scripts/seed-reels.mjs) is the AI-tagged one.
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {neon} from '@neondatabase/serverless';

const ROOT = new URL('../', import.meta.url);
const FIXTURE = new URL('db/feed-reels-fixture.json', ROOT);
const SEED_SQL = new URL('db/seed-feed-reels.sql', ROOT);
const args = process.argv.slice(2);
const LIMIT = Number(args[args.indexOf('--limit') + 1]) || 24;
const NO_DB = args.includes('--no-db');
const UA = {'User-Agent': 'meta-reels-seed/1.0 (+https://github.com/balebbae/meta)'};

const TOPICS = ['city night', 'ocean waves', 'cooking', 'dog', 'cat', 'skateboard', 'street food', 'coffee', 'concert', 'mountains', 'surfing', 'travel'];
// Keep workouts out of the general feed: they belong to the Fitness tab.
const FITNESS = /\b(workout|fitness|gym|exercise|yoga|push.?up|squat|plank|crossfit|running|jogging|training)\b/i;

async function pixabay(q) {
  const url = `https://pixabay.com/api/videos/?key=${process.env.PIXABAY_API_KEY}&q=${encodeURIComponent(q)}&video_type=film&per_page=60&safesearch=true&order=popular`;
  const res = await fetch(url, {headers: UA});
  if (!res.ok) throw new Error(`pixabay ${res.status} for ${q}`);
  return (await res.json()).hits ?? [];
}

const cap = s => s.charAt(0).toUpperCase() + s.slice(1);

function toClip(hit, topic) {
  const v = hit.videos;
  const f = v.small?.url && v.small.size < 12_000_000 ? v.small : v.tiny?.url ? v.tiny : v.medium;
  const tags = String(hit.tags ?? '')
    .split(',')
    .map(t => t.trim().toLowerCase())
    .filter(Boolean)
    .slice(0, 5);
  return {
    pixabay_id: hit.id,
    topic,
    caption: tags.length > 1 ? `${cap(tags[0])}, ${tags[1]}` : cap(tags[0] ?? topic),
    tags,
    video_url: f.url,
    poster_url: f.thumbnail,
    duration: hit.duration,
    width: f.width,
    height: f.height,
    creator_name: hit.user,
    creator_url: hit.userURL,
    source_url: hit.pageURL,
  };
}

async function fetchClips() {
  const seen = new Set();
  const byTopic = [];
  const perTopic = Math.max(1, Math.ceil(LIMIT / TOPICS.length));
  for (const topic of TOPICS) {
    const out = [];
    byTopic.push(out);
    const hits = (await pixabay(topic))
      .filter(h => h.isGRated !== false && !h.isAiGenerated && !FITNESS.test(h.tags ?? ''))
      .filter(h => h.duration >= 5 && h.duration <= 60)
      .map(h => ({h, score: (h.videos.medium.height > h.videos.medium.width ? 100 : 0) + Math.min(40, Math.log10(1 + (h.likes ?? 0)) * 10)}))
      .sort((a, b) => b.score - a.score);
    let n = 0;
    for (const {h} of hits) {
      if (n >= perTopic) break;
      if (seen.has(h.id)) continue;
      seen.add(h.id);
      out.push(toClip(h, topic));
      n++;
    }
    console.log(`${topic}: ${hits.length} usable -> ${n}`);
  }
  // Round-robin across topics so the feed doesn't play three dog clips in a row.
  const mixed = [];
  for (let i = 0; i < perTopic; i++) for (const list of byTopic) if (list[i]) mixed.push(list[i]);
  return mixed.slice(0, LIMIT);
}

const q = s => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const arr = a => (a.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const COLS = 'pixabay_id, video_url, poster_url, duration_sec, width, height, creator_name, creator_url, source_url, topic, caption, tags';

function writeSeedSql(rows) {
  const header = `-- Generated by scripts/seed-feed-reels.mjs (${new Date().toISOString().slice(0, 10)}). General "For you" Reels: Pixabay clips (credit "Video by <user> on Pixabay").\n-- Idempotent: each row is inserted only when its pixabay_id is missing. db-setup splits on ";\\n".\n\n`;
  const body = rows
    .map(r => `insert into feed_reels (${COLS})\nselect ${[r.pixabay_id, q(r.video_url), q(r.poster_url), r.duration ?? 'null', r.width ?? 'null', r.height ?? 'null', q(r.creator_name), q(r.creator_url), q(r.source_url), q(r.topic), q(r.caption), arr(r.tags)].join(', ')}\nwhere not exists (select 1 from feed_reels where pixabay_id = ${r.pixabay_id});\n`)
    .join('\n');
  writeFileSync(SEED_SQL, header + body);
}

let clips;
if (process.env.PIXABAY_API_KEY) {
  clips = await fetchClips();
  writeFileSync(FIXTURE, JSON.stringify(clips, null, 1) + '\n');
  console.log(`fetched ${clips.length} clips; fixture updated`);
} else {
  if (!existsSync(FIXTURE)) throw new Error('PIXABAY_API_KEY is not set and db/feed-reels-fixture.json is missing');
  clips = JSON.parse(readFileSync(FIXTURE, 'utf8')).slice(0, LIMIT);
  console.log(`PIXABAY_API_KEY not set; using ${clips.length} clips from the fixture`);
}
writeSeedSql(clips);
console.log(`wrote db/seed-feed-reels.sql (${clips.length} rows)`);
if (!NO_DB) {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is not set');
  const sql = neon(process.env.DATABASE_URL);
  await sql.query(readFileSync(new URL('db/schema.sql', ROOT), 'utf8').match(/create table if not exists feed_reels[\s\S]*?\);/)[0]);
  for (const r of clips) {
    await sql`
      insert into feed_reels (pixabay_id, video_url, poster_url, duration_sec, width, height, creator_name, creator_url, source_url, topic, caption, tags)
      values (${r.pixabay_id}, ${r.video_url}, ${r.poster_url}, ${r.duration}, ${r.width}, ${r.height}, ${r.creator_name}, ${r.creator_url}, ${r.source_url}, ${r.topic}, ${r.caption}, ${r.tags}::text[])
      on conflict (pixabay_id) do update set video_url = excluded.video_url, poster_url = excluded.poster_url, caption = excluded.caption, tags = excluded.tags`;
  }
  console.log(`upserted ${clips.length} feed reels`);
}
